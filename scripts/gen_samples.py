# reportlab 내장 CJK 폰트. 별도 폰트 파일 없이 한글을 렌더링한다.
KOREAN_FONT = "HYSMyeongJo-Medium"


# --------------------------------------------------------------------------
# 렌더러
# --------------------------------------------------------------------------


def _register_korean_font() -> None:
    """한글 CID 폰트를 등록한다(여러 번 불러도 안전하다)."""
    pdfmetrics.registerFont(UnicodeCIDFont(KOREAN_FONT))


# HYSMyeongJo-Medium 에 없는 글자는 PDF 에서 통째로 사라진다(추출 텍스트에서도 빠진다).
# 가운뎃점 U+00B7 이 대표적이라, 한글 가운뎃점 U+318D 로 바꿔서 렌더링한다.
_PDF_CHAR_FIXUPS = {"·": "ㆍ", "‧": "ㆍ"}


def _pdf_safe(text: str) -> str:
    """PDF 폰트가 렌더링하지 못하는 글자를 대체 글자로 바꾼다."""
    for source, replacement in _PDF_CHAR_FIXUPS.items():
        text = text.replace(source, replacement)
    return text


def write_pdf(path: Path, title: str, blocks: list[tuple[str, str]]) -> None:
    """`(스타일, 텍스트)` 블록 목록을 PDF 로 렌더링한다.

    스타일: `h1` 제목, `h2` 소제목, `p` 본문, `break` 쪽 나눔.
    """
    _register_korean_font()
    heading1 = ParagraphStyle(
        "ko-h1", fontName=KOREAN_FONT, fontSize=16, leading=24, spaceAfter=10
    )
    heading2 = ParagraphStyle(
        "ko-h2", fontName=KOREAN_FONT, fontSize=12.5, leading=19, spaceBefore=10, spaceAfter=5
    )
    body = ParagraphStyle("ko-p", fontName=KOREAN_FONT, fontSize=10.5, leading=17, spaceAfter=4)

    styles = {"h1": heading1, "h2": heading2, "p": body}
    flowables: list[object] = []
    for kind, text in blocks:
        if kind == "break":
            flowables.append(PageBreak())
            continue
        flowables.append(Paragraph(_pdf_safe(text), styles[kind]))
        if kind == "h1":
            flowables.append(Spacer(1, 4 * mm))

    document = SimpleDocTemplate(
        str(path),
        pagesize=A4,
        title=title,
        author=COMPANY,
        leftMargin=22 * mm,
        rightMargin=22 * mm,
        topMargin=22 * mm,
        bottomMargin=20 * mm,
    )
    document.build(flowables)


def write_docx(path: Path, title: str, blocks: list[tuple[str, str]]) -> None:
    """`(스타일, 텍스트)` 블록 목록을 DOCX 로 저장한다."""
    document = DocxDocument()
    document.add_heading(title, level=0)
    for kind, text in blocks:
        if kind == "h2":
            document.add_heading(text, level=1)
        elif kind == "h3":
            document.add_heading(text, level=2)
        elif kind == "li":
            document.add_paragraph(text, style="List Bullet")
        else:
            document.add_paragraph(text)
    document.save(path)


def write_xlsx(path: Path, sheets: list[tuple[str, list[list[object]]]]) -> None:
    """시트별 행 목록을 XLSX 로 저장한다. 각 시트의 첫 행은 머리글로 굵게 쓴다."""
    workbook = openpyxl.Workbook()
    workbook.remove(workbook.active)  # type: ignore[arg-type]
    for name, rows in sheets:
        sheet = workbook.create_sheet(title=name)
        for row in rows:
            sheet.append(row)
        for cell in sheet[1]:
            cell.font = Font(bold=True)
        for column_cells in sheet.columns:
            width = max((len(str(cell.value or "")) for cell in column_cells), default=8)
            sheet.column_dimensions[column_cells[0].column_letter].width = min(48, width + 4)
    workbook.save(path)


def write_md(path: Path, text: str) -> None:
    """마크다운 파일을 저장한다."""
    path.write_text(text.strip() + "\n", encoding="utf-8")


