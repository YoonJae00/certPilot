def generate_samples(output_dir: Path | None = None) -> list[Path]:
    """샘플 문서 12개를 생성하고 경로 목록을 돌려준다."""
    target = output_dir or SAMPLES_DIR
    target.mkdir(parents=True, exist_ok=True)

    written: list[Path] = []
    for filename, builder in SAMPLE_BUILDERS:
        path = target / filename
        builder(path)  # type: ignore[operator]
        written.append(path)
    return written


def main() -> int:
    """샘플을 생성하고 결과를 출력한다."""
    written = generate_samples()
    for path in written:
        print(f"  생성 {path.relative_to(REPO_ROOT)} ({path.stat().st_size:,} bytes)")
    print(f"샘플 문서 {len(written)}개 생성 완료: {SAMPLES_DIR.relative_to(REPO_ROOT)}")
    return 0


